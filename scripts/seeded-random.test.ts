const sequence = (next: () => number) => Array.from({ length: 8 }, () => next());

describe("uint32 arithmetic matches the bitwise operators", () => {
  for (const [name, words] of [
    ["editorial-charts", editorialWords],
    ["finance-charts", financeWords],
    ["terminal-disintegrate", terminalWords],
  ] as const) {
    test(name, () => {
      assert.deepEqual(INPUTS.map(words.toUint32), BITWISE.u32);
      assert.deepEqual(
        INPUTS.flatMap((value) => SHIFTS.map((bits) => words.shiftRight(value, bits))),
        BITWISE.shr,
      );
      assert.deepEqual(
        PAIRS.map(([a, b]) => words.xor(a, b)),
        BITWISE.xor,
      );
      assert.deepEqual(
        PAIRS.map(([a, b]) => words.or(a, b)),
        BITWISE.or,
      );
    });
  }
});

describe("seeded generators keep their bitwise output", () => {
  test("editorial-charts hash", () => {
    assert.deepEqual(HASH_INPUTS.map(hash), SEQUENCES.hash);
  });

  test("finance-charts mulberry32", () => {
    assert.deepEqual(
      SEEDS.map((seed) => sequence(rng(seed))),
      SEQUENCES.rng,
    );
  });

  test("terminal-disintegrate mulberry32", () => {
    assert.deepEqual(
      SEEDS.map((seed) => sequence(seededRng(seed))),
      SEQUENCES.seededRng,
    );
  });

  test("terminal-disintegrate scorch pick", () => {
    const picks = PICK_SEEDS.map((seed) => terminalWords.toUint32(seed * 2_654_435_761));

    assert.deepEqual(picks, SEQUENCES.pick);
    assert.deepEqual(
      picks.map((pick) => terminalWords.shiftRight(pick, 8) % 256),
      SEQUENCES.byte,
    );
  });
});
